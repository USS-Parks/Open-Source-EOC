// Writes web/src/cop/county-bounds.ts, the county boxes the map's find box
// searches, from the county outlines in web/public/basemap/ca_counties.geojson.
// Node standard library only. Run from anywhere: node tools/basemap/build-county-bounds.mjs
import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("../../web/public/basemap/ca_counties.geojson", import.meta.url);
const target = new URL("../../web/src/cop/county-bounds.ts", import.meta.url);

const rows = [];
for (const feature of JSON.parse(readFileSync(source, "utf8")).features) {
  const box = [Infinity, Infinity, -Infinity, -Infinity];
  const walk = (c) => {
    if (typeof c[0] === "number") {
      box[0] = Math.min(box[0], c[0]); box[1] = Math.min(box[1], c[1]);
      box[2] = Math.max(box[2], c[0]); box[3] = Math.max(box[3], c[1]);
    } else for (const inner of c) walk(inner);
  };
  walk(feature.geometry.coordinates);
  // Four decimals (about 11 m), rounded outward so the box still holds the whole county.
  const [w, s, e, n] = box;
  const out = [Math.floor(w * 1e4), Math.floor(s * 1e4), Math.ceil(e * 1e4), Math.ceil(n * 1e4)]
    .map((v) => Number((v / 1e4).toFixed(4)));
  rows.push(`  ${JSON.stringify(feature.properties.name)}: [${out.join(", ")}],`);
}
rows.sort();

writeFileSync(target, [
  "// Generated by tools/basemap/build-county-bounds.mjs from web/public/basemap/ca_counties.geojson.",
  "// Do not edit by hand; rerun the script when the county file changes.",
  "",
  "/** California county boxes for the map's find box: west, south, east, north. */",
  "export const COUNTY_BOUNDS: Record<string, [number, number, number, number]> = {",
  ...rows,
  "};",
  "",
].join("\n"));
console.log(`wrote ${rows.length} counties to web/src/cop/county-bounds.ts`);
